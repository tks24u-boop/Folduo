def text_sketch(s, px=0.8, gap=1, center=True, eps=0.03):
    """Return a Sketch of pixel text; each pixel px mm square, baseline at y=0.
    Pixels grow by eps so diagonal neighbours overlap instead of touching at a
    single corner, which would make a non-manifold mesh."""
    rects = []
    adv = (5 + gap) * px
    for i, ch in enumerate(s.upper()):
        g = F[ch]
        for r, row in enumerate(g):
            # merge horizontal runs
            c = 0
            while c < 5:
                if row[c] == '#':
                    c1 = c
                    while c1 + 1 < 5 and row[c1 + 1] == '#':
                        c1 += 1
                    w = (c1 - c + 1) * px
                    x = i * adv + c * px + w / 2
                    y = (6 - r) * px + px / 2
                    rects.append(Pos(x, y) * Rectangle(w + 2 * eps, px + 2 * eps))
                    c = c1 + 1
                else:
                    c += 1
    sk = Sketch() + rects
    if center:
        wtot = len(s) * adv - gap * px
        sk = Pos(-wtot / 2, -3.5 * px) * sk
    return sk
